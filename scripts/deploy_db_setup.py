"""One safe, idempotent command for database setup — the only DB command the deployment runbook
needs. Run this after every deploy, first time or the hundredth time:

    python3 scripts/deploy_db_setup.py

Why this exists: the migration history (migrations/versions/) only captures the *incremental*
diff from when Flask-Migrate was adopted onto this project — it assumes the base schema (Team,
Mission, EventState, etc.) already exists, because it was autogenerated against a database that
already had those tables. Running `flask db upgrade` directly against a genuinely empty database
crashes (`ALTER TABLE challenges ADD COLUMN ...` against a table that was never created — confirmed
live). The standard, correct fix for "adopting Alembic on a project with pre-existing models" is:
create the full current schema once via db.create_all(), then stamp the migration history as
already being at head (skipping replay of diffs that create_all() already satisfied). This script
detects which situation it's in and does the right thing automatically:

- Empty database (fresh Railway/Render Postgres, nothing provisioned yet): create_all() + stamp.
- Existing database (a redeploy pulling newer code with new migrations): plain `flask db upgrade`,
  which correctly applies only what's new.

Either way, the database ends up fully current and correctly stamped. Safe to run repeatedly.
"""
import os
import sys

# Running as `python3 scripts/deploy_db_setup.py` puts only scripts/ on sys.path (Python adds
# the script's own directory, not the cwd) — add the repo root so `app` resolves regardless of
# invocation.
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sqlalchemy import inspect

from app import create_app
from app.extensions import db
from flask_migrate import stamp, upgrade


def main():
    app = create_app()
    with app.app_context():
        existing_tables = set(inspect(db.engine).get_table_names())
        tracked = "alembic_version" in existing_tables

        if tracked:
            print(f"Migration-tracked database detected ({len(existing_tables)} tables) — running migrations.")
            upgrade()
            print("Done: migrations applied (or already up to date).")
        elif not existing_tables:
            print("Empty database detected — creating full current schema and stamping history.")
            db.create_all()
            stamp()
            print("Done: schema created, migration history stamped at head.")
        else:
            # Tables exist (e.g. a legacy local DB from before migration tracking was set up,
            # or one seed.py has drop_all()/create_all()'d) but migration history was never
            # stamped. Tables already match current models.py — just record that, don't replay
            # diffs that would try to re-add columns that already exist.
            print(
                f"Untracked existing database detected ({len(existing_tables)} tables, no "
                "alembic_version) — stamping current schema as up to date without replaying it."
            )
            stamp()
            print("Done: migration history stamped at head.")


if __name__ == "__main__":
    try:
        main()
    except Exception as exc:  # noqa: BLE001 — a deploy script must report failure clearly, not traceback-dump
        print(f"\nDATABASE SETUP FAILED: {type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
